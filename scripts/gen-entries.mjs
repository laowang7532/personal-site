import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { join } from 'node:path'
import { readPostMetas } from './lib/posts.mjs'

const root = process.cwd()
const postsDir = join(root, 'posts')
const GEN_MARKER = '<!-- generated by scripts/gen-entries.mjs -->'
const FAVICON =
  "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Crect width='32' height='32' rx='8' fill='%23EA580C'/%3E%3Ccircle cx='16' cy='17' r='6' fill='%23F2EFE9'/%3E%3Ccircle cx='9' cy='9' r='3.4' fill='%23F2EFE9'/%3E%3Ccircle cx='23' cy='9' r='3.4' fill='%23F2EFE9'/%3E%3Ccircle cx='14' cy='16' r='1.1' fill='%230B0B0D'/%3E%3Ccircle cx='18' cy='16' r='1.1' fill='%230B0B0D'/%3E%3C/svg%3E"

function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
}

function shell(meta) {
  const title = `${escapeHtml(meta.title)} · 小王同学`
  const description = escapeHtml(meta.summary || meta.title)

  return `<!DOCTYPE html>
${GEN_MARKER}
<html lang="zh-CN">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${description}">
<meta property="og:title" content="${escapeHtml(meta.title)}">
<meta property="og:description" content="${description}">
<meta property="og:type" content="article">
<link rel="icon" href="${FAVICON}">
</head>
<body>
<div id="app" data-page="post" data-slug="${escapeHtml(meta.slug)}"></div>
<noscript><p style="color:#F2EFE9;font-family:sans-serif;padding:24px">请启用 JavaScript 查看本站。</p></noscript>
<script type="module" src="/src/entries/post.ts"></script>
</body>
</html>
`
}

mkdirSync(postsDir, { recursive: true })

const metas = readPostMetas(root)
const published = metas.filter(meta => !meta.draft)
const expected = new Set(published.map(meta => `${meta.slug}.html`))
let written = 0

for (const meta of published) {
  const file = join(postsDir, `${meta.slug}.html`)
  const next = shell(meta)
  const current = existsSync(file) ? readFileSync(file, 'utf8') : ''
  if (current !== next) {
    writeFileSync(file, next)
    written++
    console.log(`generated  posts/${meta.slug}.html`)
  }
}

// 只清理本脚本生成、但对应 md 已删除或转草稿的入口；v1 旧文件不在此列
for (const name of readdirSync(postsDir).filter(file => file.endsWith('.html'))) {
  if (expected.has(name)) continue
  const file = join(postsDir, name)
  const source = readFileSync(file, 'utf8')
  if (source.includes(GEN_MARKER)) {
    unlinkSync(file)
    console.log(`removed    posts/${name}`)
  }
}

if (published.length === 0) {
  console.log('no published posts — skip entry generation')
} else {
  console.log(`entries: ${published.length} post(s), ${written} updated`)
}
